"""
BIM / Autodesk Revit Exporter for Isolated Footing.
Generates an executable pyRevit / Revit Python Shell script to instantiate and parameterize the footing.
"""

from pathlib import Path
from structural.foundations.isolated_footing.scripts.design_engine import FootingDesignResult


class IsolatedFootingRevitExporter:
    """Generates a Revit Python script to model the footing family in Autodesk Revit."""

    def __init__(self, result: FootingDesignResult, column_length_mm: float, column_width_mm: float):
        self.res = result
        self.col_l = column_length_mm
        self.col_w = column_width_mm

    def generate_script(self, element_name: str = "F-01") -> str:
        script = f"""# =========================================================================
# AUTODESK REVIT AUTOMATION SCRIPT (pyRevit / Revit Python Shell)
# Element: Isolated Footing {element_name}
# Active Code: {self.res.code_used}
# =========================================================================

import clr
clr.AddReference('RevitAPI')
clr.AddReference('RevitServices')

from Autodesk.Revit.DB import *
from RevitServices.Persistence import DocumentManager
from RevitServices.Transactions import TransactionManager

doc = DocumentManager.Instance.CurrentDBDocument

# Footing Parameters (Metric converted to Internal Imperial Units - Feet)
MM_TO_FEET = 0.00328084
length_ft = {self.res.length_mm} * MM_TO_FEET
width_ft = {self.res.width_mm} * MM_TO_FEET
thickness_ft = {self.res.thickness_mm} * MM_TO_FEET

TransactionManager.Instance.EnsureInTransaction(doc)

try:
    # 1. Locate Isolated Footing Family Symbol
    collector = FilteredElementCollector(doc).OfCategory(BuiltInCategory.OST_StructuralFoundation).OfClass(FamilySymbol)
    symbol = collector.FirstElement()

    if not symbol.IsActive:
        symbol.Activate()
        doc.Regenerate()

    # 2. Place Family Instance at Origin (0,0,0)
    origin = XYZ(0, 0, 0)
    level = FilteredElementCollector(doc).OfClass(Level).FirstElement()
    instance = doc.Create.NewFamilyInstance(origin, symbol, level, Structure.StructuralType.Footing)

    # 3. Set Dimensions & Comment Parameters
    type_elem = doc.GetElement(instance.GetTypeId())
    
    # Try setting length, width, thickness parameters if available
    param_l = type_elem.LookupParameter("Length") or type_elem.LookupParameter("Footing Length")
    if param_l and not param_l.IsReadOnly:
        param_l.Set(length_ft)

    param_w = type_elem.LookupParameter("Width") or type_elem.LookupParameter("Footing Width")
    if param_w and not param_w.IsReadOnly:
        param_w.Set(width_ft)

    param_t = type_elem.LookupParameter("Thickness") or type_elem.LookupParameter("Foundation Thickness")
    if param_t and not param_t.IsReadOnly:
        param_t.Set(thickness_ft)

    comment_param = instance.LookupParameter("Comments")
    if comment_param:
        comment_param.Set("Generated by AI Engineering Engine | {element_name}: {self.res.length_mm/1000.0:.2f}x{self.res.width_mm/1000.0:.2f}x{int(self.res.thickness_mm)}mm | {self.res.bars_l_count}T{self.res.bar_dia_l_mm} Long, {self.res.bars_b_count}T{self.res.bar_dia_b_mm} Short")

    print("[SUCCESS] Isolated Footing {element_name} instantiated successfully in Revit.")

except Exception as ex:
    print("[ERROR] Failed to instantiate footing in Revit: " + str(ex))

finally:
    TransactionManager.Instance.TransactionTaskDone()
"""
        return script

    def export(self, filepath: Path) -> Path:
        target = Path(filepath).resolve()
        target.parent.mkdir(parents=True, exist_ok=True)
        content = self.generate_script()
        with open(target, "w", encoding="utf-8") as f:
            f.write(content)
        return target
